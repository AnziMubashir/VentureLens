from datetime import datetime, timezone
from typing import Dict, List, Literal, Optional
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# 1. Idea Submission Input
# ---------------------------------------------------------------------------

class IdeaInput(BaseModel):
    """Input payload provided by user when submitting a new venture idea."""

    name: str = Field(..., min_length=2, max_length=100, description="Name of the venture or product")
    description: str = Field(..., min_length=10, max_length=2000, description="Brief description of the concept")
    problem: str = Field(..., min_length=10, max_length=1500, description="Specific problem being addressed")
    target_users: str = Field(..., min_length=5, max_length=1000, description="Intended customer or user segment")
    proposed_solution: str = Field(..., min_length=10, max_length=2000, description="Proposed product or service solution")


# ---------------------------------------------------------------------------
# 2. Stage 1: Specialist Agent Output Schemas
# ---------------------------------------------------------------------------

class InvestorAnalysis(BaseModel):
    """Evaluation generated by the Investor Agent."""

    perspective: Literal["investor"] = "investor"
    market_opportunity: str = Field(..., description="Assessment of market size and value proposition")
    revenue_models: List[str] = Field(..., description="Potential monetization paths")
    competitive_differentiation: str = Field(..., description="Unique selling proposition and defensibility")
    commercial_risks: List[str] = Field(..., description="Key business and market risks")
    recommendations: List[str] = Field(..., description="Commercial next steps")
    verdict: str = Field(..., description="Summary commercial outlook")


class TechnicalAnalysis(BaseModel):
    """Evaluation generated by the Technical Agent."""

    perspective: Literal["technical"] = "technical"
    feasibility_assessment: str = Field(..., description="Technical practicality and complexity")
    recommended_stack: List[str] = Field(..., description="Suggested architecture and technologies")
    architecture_overview: str = Field(..., description="High-level system design")
    mvp_scope: List[str] = Field(..., description="Core features feasible for an initial MVP")
    technical_risks: List[str] = Field(..., description="Security, scaling, or infrastructure bottlenecks")
    verdict: str = Field(..., description="Summary engineering outlook")


class UserAnalysis(BaseModel):
    """Evaluation generated by the User Agent."""

    perspective: Literal["user"] = "user"
    target_personas: List[str] = Field(..., description="Detailed profile of target users")
    core_pain_points: List[str] = Field(..., description="Validated pain points and friction")
    user_value_proposition: str = Field(..., description="Real-world benefit to end users")
    adoption_barriers: List[str] = Field(..., description="Potential barriers to initial adoption")
    key_user_features: List[str] = Field(..., description="Critical user-facing features")
    verdict: str = Field(..., description="Summary adoption outlook")


class SpecialistOutputs(BaseModel):
    """Container holding outputs from all three specialist agents."""

    investor: Optional[InvestorAnalysis] = None
    technical: Optional[TechnicalAnalysis] = None
    user: Optional[UserAnalysis] = None


# ---------------------------------------------------------------------------
# 3. Stage 2: Main Agent Initial Synthesis
# ---------------------------------------------------------------------------

class InitialSynthesis(BaseModel):
    """Initial consolidation of findings generated by the Main Agent (Board Chair)."""

    executive_summary: str = Field(..., description="High-level overview of the board's findings")
    key_agreements: List[str] = Field(..., description="Points where specialists broadly agree")
    conflicting_perspectives: List[str] = Field(..., description="Areas where recommendations or priorities clash")
    cross_dependencies: List[str] = Field(..., description="Dependencies identified between domains")


# ---------------------------------------------------------------------------
# 4. Stage 3 & 4: Challenge My Idea (Critiques & Final Refined Synthesis)
# ---------------------------------------------------------------------------

class CritiqueItem(BaseModel):
    """A single critique from one specialist agent targeting another's recommendation."""

    source_agent: Literal["investor", "technical", "user"] = Field(..., description="Agent presenting the challenge")
    target_agent: Literal["investor", "technical", "user"] = Field(..., description="Agent whose claim is challenged")
    challenged_claim: str = Field(..., description="The specific claim or assumption under scrutiny")
    concern: str = Field(..., description="Why this claim is problematic or risky")
    suggested_pivot: str = Field(..., description="Recommended adjustment to resolve the concern")


class ChallengeAnalysis(BaseModel):
    """Collection of cross-agent critiques."""

    critiques: List[CritiqueItem] = Field(default_factory=list, description="List of cross-agent critiques")


class RefinedAnalysis(BaseModel):
    """Final synthesis synthesized by the Board Chair after the challenge stage."""

    synthesized_strengths: List[str] = Field(..., description="Defensible strengths validated across all perspectives")
    critical_risks: List[str] = Field(..., description="Primary unmitigated risks identified by the board")
    trade_offs_made: List[str] = Field(..., description="Explicit trade-offs resolved between conflicting agent views")
    refined_recommendations: List[str] = Field(..., description="Actionable next steps post-challenge")
    actionable_mvp: List[str] = Field(..., description="Essential feature list for MVP with deferred items noted")
    final_chair_verdict: str = Field(..., description="Decisive closing assessment by the Board Chair")


# ---------------------------------------------------------------------------
# 5. Deliverables Schemas
# ---------------------------------------------------------------------------

class PitchFeature(BaseModel):
    title: str
    description: str


class PitchContent(BaseModel):
    """Structured content used to populate the static pitch website."""

    headline: str
    tagline: str
    problem_statement: str
    solution_overview: str
    target_audiences: List[str]
    key_features: List[PitchFeature]
    business_model: str
    call_to_action: str


# ---------------------------------------------------------------------------
# 6. Overall Pitch Record State
# ---------------------------------------------------------------------------

PipelineStatus = Literal[
    "idle",
    "stage1_running",
    "stage1_complete",
    "stage2_running",
    "awaiting_challenge",
    "stage3_running",
    "stage4_running",
    "completed",
    "failed",
]


class PitchRecord(BaseModel):
    """Complete in-memory state for a venture evaluation session."""

    id: str
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    idea: IdeaInput
    status: PipelineStatus = "idle"
    stage1_specialists: Optional[SpecialistOutputs] = None
    stage2_initial_synthesis: Optional[InitialSynthesis] = None
    stage3_challenge: Optional[ChallengeAnalysis] = None
    stage4_refined_analysis: Optional[RefinedAnalysis] = None
    pitch_content: Optional[PitchContent] = None
    boardroom_report_md: Optional[str] = None
    pitch_site_html: Optional[str] = None
    error: Optional[str] = None


# ---------------------------------------------------------------------------
# 7. Sample Idea Payload
# ---------------------------------------------------------------------------

class SampleIdea(BaseModel):
    id: str
    name: str
    description: str
    problem: str
    target_users: str
    proposed_solution: str
